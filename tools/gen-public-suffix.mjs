// Usage: node tools/gen-public-suffix.mjs [--check] [path-to-public_suffix_list.dat]
// Writes packages/core/scopes/proofs/public-suffix-list.ts from the Public Suffix List
// (https://publicsuffix.org), ICANN and private sections alike. Without a path it fetches the list.
// --check exits non-zero when the committed file differs from what the list produces now.
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { join } from "node:path";

const SOURCE = "https://raw.githubusercontent.com/publicsuffix/list/main/public_suffix_list.dat";
const OUT = join(import.meta.dirname, "../packages/core/scopes/proofs/public-suffix-list.ts");

const args = process.argv.slice(2);
const check = args.includes("--check");
const path = args.find((a) => !a.startsWith("--"));
const text = path ? readFileSync(path, "utf8") : await (await fetch(SOURCE)).text();

const version = /^\/\/ VERSION: (.+)$/m.exec(text)?.[1] ?? "unknown";
const commit = /^\/\/ COMMIT: (.+)$/m.exec(text)?.[1] ?? "unknown";
const plain = new Set();
const wildcards = new Set();
const exceptions = new Set();
for (const raw of text.split("\n")) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith("//")) continue;
  const kind = line.startsWith("!") ? exceptions : line.startsWith("*.") ? wildcards : plain;
  const rule = domainToASCII(line.replace(/^(!|\*\.)/, ""));
  if (rule) kind.add(rule);
}
const join_ = (set) => JSON.stringify([...set].sort().join(" "));

const body = `// Generated by tools/gen-public-suffix.mjs from the Public Suffix List; do not edit by hand.
// Source: ${SOURCE} (Mozilla Public License 2.0).${version === "unknown" ? "" : ` List version ${version}, commit ${commit}.`}

/** Plain rules, as space-separated punycode suffixes. */
export const PLAIN_RULES: string = ${join_(plain)};

/** Wildcard rules without the leading "*.": every label under these is a suffix. */
export const WILDCARD_RULES: string = ${join_(wildcards)};

/** Exception rules without the leading "!": these are registrable although a wildcard covers them. */
export const EXCEPTION_RULES: string = ${join_(exceptions)};
`;

if (check) {
  const current = readFileSync(OUT, "utf8");
  if (current !== body) {
    console.error("public-suffix-list.ts is out of date; run node tools/gen-public-suffix.mjs");
    process.exitCode = 1;
  }
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}: ${plain.size} rules, ${wildcards.size} wildcards, ${exceptions.size} exceptions (${version})`);
}
