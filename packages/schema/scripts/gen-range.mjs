// Generates src/range.ts (SCHEMA_MIN..SCHEMA_MAX, REQ-OPS-011) from the migrations directory.
// Usage: node scripts/gen-range.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const CONTRACT_MARKER = /^--\s*contract-of:\s*(\S+\.sql)\s*$/m;

export function migrationFiles(dir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort();
}

const stamp = (file) => file.slice(0, file.indexOf("_"));

/** MIN is the newest contract migration (the code no longer reads the shape it retired), else the first migration. */
export function renderRange(dir) {
  const files = migrationFiles(dir);
  if (files.length === 0) throw new Error(`no migrations in ${dir}`);
  const contracts = files.filter((f) => CONTRACT_MARKER.test(readFileSync(join(dir, f), "utf8")));
  const min = stamp(contracts.at(-1) ?? files[0]);
  const max = stamp(files.at(-1));
  return `// Generated by scripts/gen-range.mjs from migrations/; run \`pnpm --filter @packserver/schema gen:range\`, never edit.
export const SCHEMA_MIN = "${min}";
export const SCHEMA_MAX = "${max}";
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(import.meta.dirname, "..");
  const target = join(root, "src/range.ts");
  const next = renderRange(join(root, "migrations"));
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== next) {
      console.error("src/range.ts is out of date; run pnpm --filter @packserver/schema gen:range");
      process.exitCode = 1;
    }
  } else {
    writeFileSync(target, next);
  }
}
